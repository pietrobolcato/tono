#!/usr/bin/env python3
"""Restore the fine detail of the existing four-second woodland field recording."""
from array import array
import hashlib, math, re, subprocess, sys
from pathlib import Path
root=Path(__file__).resolve().parents[2]
source=Path(sys.argv[1])
if hashlib.sha256(source.read_bytes()).hexdigest() != 'bfdef90ca4cf5bdf5adbce7abb9432948e8ec0c7e54417f8ab23a65900161001':
    raise ValueError('Expected the CC0 ForestRainShower1a HQ preview listed in README.md')

# Recover the *actual* factory low-band playback, including its quantisation.
# This lets the extra bitstream correct that error as well as restoring highs.
header=(root/'firmware/src/amb_rain_drops.h').read_text()
def data(name):
    return list(map(int,re.search(name+r'\[\d+\]=\{(.*?)\};',header,re.S)[1].strip().strip(',').split(',')))
pcm,scale=data('rain_forest'),data('rain_scales')
lo=[(1,4,-1,-4)[pcm[j>>2]>>((j&3)*2)&3]*scale[j>>5] for j in range(16384)]
numerator,denominator=11,4
rate=4096*numerator//denominator
take=array('h',subprocess.check_output(['ffmpeg','-v','error','-ss','45.744','-i',str(source),'-t','4','-ar',str(rate),'-ac','1','-f','s16le','-']))
if sys.byteorder!='little':take.byteswap()
assert len(take)*denominator==len(lo)*numerator
base=[]
for i in range(len(take)):
    j,rem=divmod(i*denominator,numerator)
    base.append(lo[j]+(lo[min(j+1,len(lo)-1)]-lo[j])*rem/numerator)
gain=sum(x*y for x,y in zip(take,base))/sum(y*y for y in base)
res=[x/gain-y for x,y in zip(take,base)]
stride=128
levels=[sum(map(abs,res[i:i+stride]))/stride for i in range(0,len(res),stride)]
unit=max(1,math.ceil(max(levels)/255))
levels=[round(v/unit) for v in levels]
codes=[sum(int(res[i+j]>=0)<<j for j in range(8)) for i in range(0,len(res),8)]
out=['/* SPDX-License-Identifier: CC0-1.0 */','/* Generated by tools/field/wet_surface.py. */',
     f'enum {{WET_NUM={numerator}, WET_DEN={denominator}, WET_FRAMES={len(take)}, WET_UNIT={unit}}};']
for key,values in [('wet_detail',codes),('wet_level',levels)]:
    out.append(f'static const uint8_t {key}[{len(values)}]={{')
    out.extend('    '+','.join(map(str,values[j:j+24]))+',' for j in range(0,len(values),24))
    out.append('};')
(root/'firmware/src/amb_wet_field.h').write_text('\n'.join(out)+'\n')
