"""Rebuild Tono's CC0 mono instrument excerpts using ffmpeg and the Python stdlib."""
import array
import hashlib
import io
import math
import statistics
from pathlib import Path
import subprocess
import sys
import tempfile
from urllib.parse import quote
from urllib.request import urlopen

VSCO = ("VSCO-2-CE", "440300901dfe9275fd84e0b7763af1f8443ae62e")
VCSL = ("VCSL", "c1ea7bcc3c7309650ab0da9d15c9cd1fbc4a4c7e")
SOURCES = [
    ("violin", VSCO, "Strings/Solo Violin/Arco Vib/LLVln_ArcoVib_C4_p.wav", 12288),
    ("cello", VSCO, "Strings/Cello Section/susvib/susvib_C3_v1_1.wav", 39970),
    ("piano", VCSL, "Chordophones/Zithers/Grand Piano, Kawai/Sustains/GPiano_sus_C4_v2_rr1_Player.wav", 21504),
    ("tenor", VCSL, "Aerophones/Reed Aerophones/Tenor Saxophone/Non-Vibrato/BrettTenor_NV_Main_C4_vl2_rr1.wav", 11264),
    ("flute", VSCO, "Woodwinds/Flute/susNV/LDFlute_susNV_C4_v1_1.wav", 9216),
]
def steady_cello_sustain(values):
    # Treat the body and bow noise separately so a dip in the fundamental
    # does not lift a periodic scrape. The symmetric split adds no delay.
    attack, blend = 3072, 768
    def moving_average(signal, radius):
        prefix = [0]
        for sample in signal:
            prefix.append(prefix[-1] + sample)
        result = []
        for i in range(len(signal)):
            lo, hi = max(0, i-radius), min(len(signal), i+radius+1)
            result.append((prefix[hi]-prefix[lo])/(hi-lo))
        return result

    body = moving_average(values, 8)
    bow = [x-y for x, y in zip(values, body)]
    sustain = [0.0] * len(values)
    for band in (body, bow):
        power = moving_average([x*x for x in band], 240)
        target = statistics.median(power[attack+blend:])
        for i in range(attack, len(values)):
            gain = min(2.0, max(0.5, math.sqrt(target/max(1, power[i]))))
            sustain[i] += band[i]*gain
    result = values.copy()
    for i in range(attack, len(values)):
        mix = min(1, (i-attack)/blend)
        result[i] = round(values[i] + mix*(sustain[i]-values[i]))
    return result


out = io.StringIO()
out.write("/* SPDX-License-Identifier: CC0-1.0 */\n/* Generated by tools/gen_amb_acoustic.py. Mono recordings. Cello: 12000 Hz, 8-bit companded. Others: 16000 Hz, signed PCM. */\n")
for name, (repo, revision), path, count in SOURCES:
    url = f"https://raw.githubusercontent.com/sgossner/{repo}/{revision}/{quote(path)}"
    with tempfile.NamedTemporaryFile(suffix=".wav") as wav:
        wav.write(urlopen(url, timeout=45).read())
        wav.flush()
        pcm = subprocess.check_output(["ffmpeg", "-v", "error", "-i", wav.name, "-ac", "1", "-ar", "12000" if name == "cello" else "16000", "-f", "s16le", "-"])
    samples = array.array("h", pcm)
    if sys.byteorder != "little":
        samples.byteswap()
    threshold = max(map(abs, samples)) // 180
    start = max(0, next(i for i,x in enumerate(samples) if abs(x)>threshold)-96)
    excerpt = samples[start:start+count]
    assert len(excerpt)==count
    peak = max(map(abs, excerpt))
    values = [round(x*20000/peak) for x in excerpt]
    if name == "cello":
        values = steady_cello_sustain(values)
        # Symmetric mu-law quantisation. Store one byte per sample and decode
        # by lookup so transposed playback can still address any sample.
        levels = [round(32767 * math.expm1(i / 127 * math.log(256)) / 255) for i in range(128)]
        decode = [-v for v in reversed(levels)] + levels
        out.write("static const int16_t amb_cello_decode[256] = {\n")
        for i in range(0, 256, 16):
            out.write("    " + ",".join(map(str, decode[i:i+16])) + ",\n")
        out.write("};\n")
        def encode(x):
            magnitude = min(127, round(127 * math.log1p(255 * abs(x) / 32767) / math.log(256)))
            return 127 - magnitude if x < 0 else 128 + magnitude
        values = [encode(x) for x in values]
    element = "uint8_t" if name == "cello" else "int16_t"
    out.write(f"static const {element} amb_pcm_{name}[{count}] = {{\n")
    for i in range(0, count, 16):
        out.write("    "+",".join(map(str,values[i:i+16]))+",\n")
    out.write("};\n")
    print(name, hashlib.sha256(pcm).hexdigest(), flush=True)
Path(__file__).resolve().parents[1].joinpath("firmware/src/amb_acoustic_pcm.h").write_text(out.getvalue())
