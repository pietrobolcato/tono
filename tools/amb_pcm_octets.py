"""Pack Tono's checked-in raw acoustic/sample assets into seekable eight-point groups."""
import io
import re
from pathlib import Path

from amb_pcm_pack import write_array

SRC = Path(__file__).resolve().parents[1] / "firmware/src"


def groups(values, period):
    data = bytearray()
    widths = []
    offsets = []
    for start in range(0, len(values), 8 * period):
        for phase in range(min(period, len(values) - start)):
            row = values[start+phase:start+8*period:period]
            # Repeating the final sample only pads the final incomplete cycle.
            row += [row[-1]] * (8 - len(row))
            base = min(row)
            width = (max(row) - base).bit_length()
            if len(widths) % 8 == 0:
                offsets.append(len(data))
            if width >= 7:
                widths.append(7)
                data.extend(row)
            else:
                widths.append(width)
                bits = sum((value - base) << (i * width) for i, value in enumerate(row))
                data.append(base)
                data.extend(bits.to_bytes(width, "little"))
    # Two lookahead bytes also cover the zero-width final group.
    data.extend(b"\x00\x00")
    directory = [sum(w << (4*n) for n,w in enumerate(widths[i:i+8]))
                 for i in range(0,len(widths),8)]
    assert len(data) <= 65536
    return data, offsets, directory


def assets():
    samples = (SRC / 'amb_samples.h').read_text().split('= {', 1)[1]
    chime, vowel = [list(map(int, re.findall(r'\d+', row))) for row in re.findall(r'\{([^{}]+)\}', samples)]
    acoustic = (SRC / 'amb_acoustic_pcm.h').read_text()
    yield 'chime', 107, chime
    yield 'vowel', 107, vowel
    for name, period in [('violin',38),('tenor',19)]:
        samples = re.search(r'amb_pcm_'+name+r'\[\d+\] = \{([^}]+)', acoustic).group(1)
        yield name, period, list(map(int,re.findall(r'\d+',samples)))
    # Decode the checked-in sixteen-point assets exactly before changing
    # their storage stride. The decoded codes and the playback rates stay fixed.
    for name, period in [('cello',46),('flute',19)]:
        symbol = 'amb_pcm_' + name
        def values(suffix):
            raw = re.search(symbol + suffix + r'\[\d+\] = \{([^}]+)', acoustic)[1]
            return list(map(int, re.findall(r'\d+', raw)))
        data, offsets, widths = (values(s) for s in ('', '_offsets', '_widths'))
        length = int(re.search(symbol + r'_length = (\d+)', acoustic)[1])
        codes = []
        for sample in range(length):
            cycle, phase = divmod(sample, period)
            row, slot = divmod((cycle // 16) * period + phase, 8)
            sizes = [(widths[row] >> (4*i)) & 15 for i in range(8)]
            offset = offsets[row] + slot + 2 * sum(sizes[:slot])
            bit = (cycle % 16) * sizes[slot]
            address = offset + 1 + bit // 8
            bits = data[address] | (data[address+1] << 8)
            codes.append(data[offset] + ((bits >> (bit % 8)) & ((1 << sizes[slot])-1)))
        yield name, period, codes


def main():
    out = io.StringIO()
    out.write('/* Generated by tools/amb_pcm_octets.py. Original Tono examples GPL-3.0-only, acoustic recordings CC0-1.0. */\n')
    for name, period, values in assets():
        data, offsets, directory = groups(values, period)
        symbol = 'amb_oct_' + name
        out.write(f'enum {{ {symbol}_length = {len(values)}, {symbol}_period = {period} }};\n')
        write_array(out, 'uint16_t', symbol+'_offsets', offsets)
        write_array(out, 'uint32_t', symbol+'_widths', directory)
        write_array(out, 'uint8_t', symbol, data)
        print(name, len(values), '->', len(data)+2*len(offsets)+4*len(directory))
    (SRC / 'amb_pcm_octets_data.h').write_text(out.getvalue())


if __name__ == '__main__':
    main()
